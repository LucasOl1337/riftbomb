import { access, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const championsRoot = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.dirname(championsRoot);
const outputPath = path.join(repositoryRoot, "game", "load-champion-sfx.js");

const playableChampions = ["katarina", "zed", "renekton", "vladimir", "gangplank"];

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function dataUrl(absolutePath) {
  const buffer = await readFile(absolutePath);
  const extension = path.extname(absolutePath).toLowerCase();
  const mime = extension === ".wav"
    ? "audio/wav"
    : extension === ".ogg"
      ? "audio/ogg"
      : extension === ".m4a" || extension === ".mp4"
        ? "audio/mp4"
        : extension === ".webm"
          ? "audio/webm"
          : "audio/mpeg";
  return `data:${mime};base64,${buffer.toString("base64")}`;
}

/**
 * Pack every champions/<name>/sfx bank that has a sfx-map.json.
 * Only files that exist on disk are embedded; empty maps still emit metadata.
 */
export async function packageChampionSfx(root = repositoryRoot) {
  const sources = {};
  const meta = {};
  const maps = {};

  for (const champion of playableChampions) {
    const sfxDirectory = path.join(root, "champions", champion, "sfx");
    const mapPath = path.join(sfxDirectory, "sfx-map.json");
    if (!(await fileExists(mapPath))) continue;

    const map = JSON.parse(await readFile(mapPath, "utf8"));
    maps[champion] = {
      champion: map.champion || champion,
      locale: map.locale || "pt_BR",
      actions: Object.keys(map.actions || {})
    };

    for (const [actionKey, action] of Object.entries(map.actions || {})) {
      const effect = action.gameEffect || actionKey;
      const files = Array.isArray(action.files) ? action.files : [];
      const embedded = [];
      for (const relativePath of files) {
        const absolutePath = path.join(sfxDirectory, relativePath);
        if (!(await fileExists(absolutePath))) {
          console.warn(`[champion-sfx] Missing ${champion}/${relativePath} — skip`);
          continue;
        }
        embedded.push(await dataUrl(absolutePath));
      }
      if (embedded.length) sources[effect] = embedded.length === 1 ? embedded[0] : embedded;
      const kind = action.lolsound?.kind || action.kind || "voice";
      const isVoice = action.voice !== false && kind !== "sfx" && kind !== "sfx-or-impact";
      meta[effect] = {
        champion,
        gain: Number.isFinite(action.gain) ? action.gain : 0.6,
        reverb: Number.isFinite(action.reverb) ? action.reverb : 0.16,
        preferSample: action.preferSample !== false,
        voice: isVoice,
        force: action.force === true || effect === "championDeath" || effect === "deathLotus",
        variants: embedded.length
      };
    }
  }

  const source = `"use strict";

// Generated by champions/package-champion-sfx.mjs — per-champion sample banks.
// Maps live in champions/<name>/sfx/sfx-map.json. Provenance per champion folder.
const RIFTBOMB_CHAMPION_SFX_SOURCES = Object.freeze(${JSON.stringify(sources)});
const RIFTBOMB_CHAMPION_SFX_META = Object.freeze(${JSON.stringify(meta)});
const RIFTBOMB_CHAMPION_SFX_MAPS = Object.freeze(${JSON.stringify(maps)});
`;

  await writeFile(path.join(root, "game", "load-champion-sfx.js"), source);
  return {
    outputPath: path.join(root, "game", "load-champion-sfx.js"),
    champions: Object.keys(maps),
    sampleEffects: Object.keys(sources),
    meta
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const result = await packageChampionSfx();
  console.log(
    `Packed champion SFX for [${result.champions.join(", ") || "none"}]; ` +
    `${result.sampleEffects.length} effect sample banks → game/load-champion-sfx.js`
  );
}
