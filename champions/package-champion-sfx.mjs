import { access, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const championsRoot = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.dirname(championsRoot);
const outputPath = path.join(repositoryRoot, "game", "load-champion-sfx.js");
const generatedBankName = "riftbomb-sfx-bank.js";

const playableChampions = ["katarina", "zed", "renekton", "vladimir", "gangplank"];
const bankEnabled = Object.freeze({ katarina: false });

async function fileExists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function dataUrl(absolutePath) {
  const buffer = await readFile(absolutePath);
  const extension = path.extname(absolutePath).toLowerCase();
  const mime = extension === ".wav"
    ? "audio/wav"
    : extension === ".ogg"
      ? "audio/ogg"
      : extension === ".m4a" || extension === ".mp4"
        ? "audio/mp4"
        : extension === ".webm"
          ? "audio/webm"
          : "audio/mpeg";
  return `data:${mime};base64,${buffer.toString("base64")}`;
}

async function writeGenerated(filePath, contents) {
  for (let attempt = 1; attempt <= 6; attempt += 1) {
    try {
      await writeFile(filePath, contents);
      return;
    } catch (error) {
      const mayBeLocked = ["EACCES", "EPERM", "UNKNOWN"].includes(error?.code);
      if (!mayBeLocked || attempt === 6) throw error;
      // Windows scanners may briefly hold a generated audio script after a build.
      await new Promise((resolve) => setTimeout(resolve, attempt * 100));
    }
  }
}

/**
 * Pack every champions/<name>/sfx bank that has a sfx-map.json.
 * Only files that exist on disk are embedded; empty maps still emit metadata.
 */
export async function packageChampionSfx(root = repositoryRoot) {
  const banks = {};

  await Promise.all(playableChampions.map((champion) =>
    rm(path.join(root, "champions", champion, "sfx", generatedBankName), { force: true })
  ));

  for (const champion of playableChampions) {
    const sfxDirectory = path.join(root, "champions", champion, "sfx");
    const mapPath = path.join(sfxDirectory, "sfx-map.json");
    if (!(await fileExists(mapPath))) continue;

    const map = JSON.parse(await readFile(mapPath, "utf8"));
    const sources = {};
    const meta = {};
    const mapMetadata = {
      champion: map.champion || champion,
      locale: map.locale || "pt_BR",
      actions: Object.keys(map.actions || {})
    };

    for (const [actionKey, action] of Object.entries(map.actions || {})) {
      const effect = action.gameEffect || actionKey;
      const files = Array.isArray(action.files) ? action.files : [];
      const embedded = [];
      for (const relativePath of files) {
        const absolutePath = path.join(sfxDirectory, relativePath);
        if (!(await fileExists(absolutePath))) {
          console.warn(`[champion-sfx] Missing ${champion}/${relativePath} — skip`);
          continue;
        }
        embedded.push(await dataUrl(absolutePath));
      }
      if (embedded.length) sources[effect] = embedded.length === 1 ? embedded[0] : embedded;
      const kind = action.lolsound?.kind || action.kind || "voice";
      const isVoice = action.voice !== false && kind !== "sfx" && kind !== "sfx-or-impact";
      meta[effect] = {
        champion,
        gain: Number.isFinite(action.gain) ? action.gain : 0.6,
        reverb: Number.isFinite(action.reverb) ? action.reverb : 0.16,
        preferSample: action.preferSample !== false,
        voice: isVoice,
        force: action.force === true || effect === "championDeath" || effect === "deathLotus",
        variants: embedded.length
      };
    }

    banks[champion] = {
      sources,
      meta,
      map: mapMetadata
    };
  }

  const manifest = {};
  let sampleEffectCount = 0;
  for (const [champion, bank] of Object.entries(banks)) {
    const source = `"use strict";

// CHAMPION_SFX_SPLIT_V1 — generated by champions/package-champion-sfx.mjs.
// Maps live in champions/<name>/sfx/sfx-map.json. Provenance per champion folder.
globalThis.RIFTBOMB_CHAMPION_SFX_BANKS = globalThis.RIFTBOMB_CHAMPION_SFX_BANKS || Object.create(null);
globalThis.RIFTBOMB_CHAMPION_SFX_BANKS[${JSON.stringify(champion)}] = Object.freeze(${JSON.stringify(bank)});
`;
    const bankPath = path.join(root, "champions", champion, "sfx", generatedBankName);
    await mkdir(path.dirname(bankPath), { recursive: true });
    await writeGenerated(bankPath, source);
    manifest[champion] = `./champions/${champion}/sfx/${generatedBankName}`;
    sampleEffectCount += Object.keys(bank.sources).length;
  }

  const loader = `"use strict";

// CHAMPION_SFX_SPLIT_V1 — keep large voice banks out of the critical HTML.
const RIFTBOMB_CHAMPION_SFX_BANK_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});
// KATARINA_SFX_SLEEP_V1 — keep the packaged bank intact, but do not load it
// until it is retuned and explicitly re-enabled.
const RIFTBOMB_CHAMPION_SFX_BANK_ENABLED = Object.freeze(${JSON.stringify(bankEnabled, null, 2)});
globalThis.RIFTBOMB_CHAMPION_SFX_BANK_MANIFEST = RIFTBOMB_CHAMPION_SFX_BANK_MANIFEST;
globalThis.RIFTBOMB_CHAMPION_SFX_BANK_ENABLED = RIFTBOMB_CHAMPION_SFX_BANK_ENABLED;
globalThis.RIFTBOMB_CHAMPION_SFX_BANKS = globalThis.RIFTBOMB_CHAMPION_SFX_BANKS || Object.create(null);
`;
  await writeGenerated(path.join(root, "game", "load-champion-sfx.js"), loader);
  return {
    outputPath: path.join(root, "game", "load-champion-sfx.js"),
    champions: Object.keys(banks),
    sampleEffects: sampleEffectCount
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const result = await packageChampionSfx();
  console.log(
    `Packed champion SFX for [${result.champions.join(", ") || "none"}]; ` +
    `${result.sampleEffects} effect sample banks → game/load-champion-sfx.js + champion SFX chunks`
  );
}
