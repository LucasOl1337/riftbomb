import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const gameDirectory = path.dirname(fileURLToPath(import.meta.url));
const assetsDirectory = path.join(gameDirectory, "Assets", "textures");
const outputPath = path.join(gameDirectory, "load-arena-textures.js");

const sources = {
  crateSide: "crates/crate-albedo.webp",
  crateTop: "crates/crate-top-albedo.webp",
  floor: "ground/floor-lattice.webp",
  wallSide: "walls/wall-lattice.webp",
  wallTop: "walls/wall-top-lattice.webp"
};

async function dataUrl(relativePath) {
  const buffer = await readFile(path.join(assetsDirectory, relativePath));
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

const packed = Object.fromEntries(
  await Promise.all(Object.entries(sources).map(async ([key, relativePath]) => [key, await dataUrl(relativePath)]))
);

const source = `"use strict";

// Generated by pack-arena-textures.mjs. Shared sources keep the single-file build compact.
const ARENA_TEXTURE_SOURCE = Object.freeze(${JSON.stringify(packed)});

const ARENA_TEXTURES = Object.freeze({
  crate: ARENA_TEXTURE_SOURCE.crateSide,
  crateTop: ARENA_TEXTURE_SOURCE.crateTop,
  floorLattice: ARENA_TEXTURE_SOURCE.floor,
  floorClearing: ARENA_TEXTURE_SOURCE.floor,
  floorLabyrinth: ARENA_TEXTURE_SOURCE.floor,
  floorForts: ARENA_TEXTURE_SOURCE.floor,
  floorPit: ARENA_TEXTURE_SOURCE.floor,
  wallLattice: ARENA_TEXTURE_SOURCE.wallSide,
  wallClearing: ARENA_TEXTURE_SOURCE.wallSide,
  wallLabyrinth: ARENA_TEXTURE_SOURCE.wallSide,
  wallForts: ARENA_TEXTURE_SOURCE.wallSide,
  wallPit: ARENA_TEXTURE_SOURCE.wallSide,
  wallTopLattice: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopClearing: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopLabyrinth: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopForts: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopPit: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopStone: ARENA_TEXTURE_SOURCE.wallTop,
  wallTopMetal: ARENA_TEXTURE_SOURCE.wallTop
});
`;

await writeFile(outputPath, source);
console.log(`Packed ${Object.keys(packed).length} arena texture sources → ${path.relative(gameDirectory, outputPath)}`);
