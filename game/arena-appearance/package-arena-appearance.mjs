import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const arenaAppearanceDirectory = path.dirname(fileURLToPath(import.meta.url));
const texturesDirectory = path.join(arenaAppearanceDirectory, "textures");
const outputPath = path.join(arenaAppearanceDirectory, "load-arena-appearance.js");

// Full modular kit: every arena has dedicated floor + wall side + wall top.
const sources = {
  crateSide: "crates/crate-albedo.webp",
  crateTop: "crates/crate-top-albedo.webp",
  floorLattice: "ground/floor-salt-lens-combat-band-6ffb0854.webp",
  floorClearing: "ground/floor-clearing.webp",
  floorLabyrinth: "ground/floor-labyrinth.webp",
  floorForts: "ground/floor-forts.webp",
  floorPit: "ground/floor-pit.webp",
  wallLattice: "walls/wall-lattice.webp",
  wallClearing: "walls/wall-clearing.webp",
  wallLabyrinth: "walls/wall-labyrinth.webp",
  wallForts: "walls/wall-forts.webp",
  wallPit: "walls/wall-pit.webp",
  wallTopLattice: "walls/wall-top-lattice.webp",
  wallTopClearing: "walls/wall-top-clearing.webp",
  wallTopLabyrinth: "walls/wall-top-labyrinth.webp",
  wallTopForts: "walls/wall-top-forts.webp",
  wallTopPit: "walls/wall-top-pit.webp"
};

async function dataUrl(relativePath) {
  const buffer = await readFile(path.join(texturesDirectory, relativePath));
  return `data:image/webp;base64,${buffer.toString("base64")}`;
}

const packed = Object.fromEntries(
  await Promise.all(Object.entries(sources).map(async ([key, relativePath]) => [key, await dataUrl(relativePath)]))
);

const source = `"use strict";

// Generated by package-arena-appearance.mjs. Full modular kit: 5 floors + 5 wall pairs + crates.
const ARENA_TEXTURE_SOURCE = Object.freeze(${JSON.stringify(packed)});

const ARENA_TEXTURES = Object.freeze({
  crate: ARENA_TEXTURE_SOURCE.crateSide,
  crateTop: ARENA_TEXTURE_SOURCE.crateTop,
  floorLattice: ARENA_TEXTURE_SOURCE.floorLattice,
  floorClearing: ARENA_TEXTURE_SOURCE.floorClearing,
  floorLabyrinth: ARENA_TEXTURE_SOURCE.floorLabyrinth,
  floorForts: ARENA_TEXTURE_SOURCE.floorForts,
  floorPit: ARENA_TEXTURE_SOURCE.floorPit,
  wallLattice: ARENA_TEXTURE_SOURCE.wallLattice,
  wallClearing: ARENA_TEXTURE_SOURCE.wallClearing,
  wallLabyrinth: ARENA_TEXTURE_SOURCE.wallLabyrinth,
  wallForts: ARENA_TEXTURE_SOURCE.wallForts,
  wallPit: ARENA_TEXTURE_SOURCE.wallPit,
  wallTopLattice: ARENA_TEXTURE_SOURCE.wallTopLattice,
  wallTopClearing: ARENA_TEXTURE_SOURCE.wallTopClearing,
  wallTopLabyrinth: ARENA_TEXTURE_SOURCE.wallTopLabyrinth,
  wallTopForts: ARENA_TEXTURE_SOURCE.wallTopForts,
  wallTopPit: ARENA_TEXTURE_SOURCE.wallTopPit,
  wallTopStone: ARENA_TEXTURE_SOURCE.wallTopLattice,
  wallTopMetal: ARENA_TEXTURE_SOURCE.wallTopLabyrinth
});
`;

await writeFile(outputPath, source);
console.log(`Packed ${Object.keys(packed).length} arena texture sources → ${path.basename(outputPath)}`);
