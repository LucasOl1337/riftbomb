import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const arenaAppearanceDirectory = path.dirname(fileURLToPath(import.meta.url));
const audioDirectory = path.join(arenaAppearanceDirectory, "audio");
const outputPath = path.join(arenaAppearanceDirectory, "load-arena-sfx.js");

const sources = {
  explosion: "arena-bomb-explosion.mp3"
};

async function dataUrl(relativePath) {
  const buffer = await readFile(path.join(audioDirectory, relativePath));
  return `data:audio/mpeg;base64,${buffer.toString("base64")}`;
}

const packed = Object.fromEntries(
  await Promise.all(Object.entries(sources).map(async ([key, relativePath]) => [key, await dataUrl(relativePath)]))
);

const source = `"use strict";

// Generated by package-arena-sfx.mjs — sample sources for arena bomb SFX.
// Provenance: game/arena-appearance/audio/PROVENANCE.md
const RIFTBOMB_ARENA_SFX_SOURCES = Object.freeze(${JSON.stringify(packed)});
`;

await writeFile(outputPath, source);
console.log(`Packed ${Object.keys(packed).length} arena SFX sources → ${path.basename(outputPath)}`);
