import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const fxDir = path.join(dir, "textures", "fx", "explosion");
const outputPath = path.join(dir, "load-explosion-frames.js");

// Named roles for Bomberman corridor VFX — multi-frame morph + arm sequence.
const frameFiles = {
  coreCross: "00-core-cross.webp",
  armCorridor: "01-arm-corridor.webp",
  armPeak: "02-arm-peak.webp",
  corePeak: "03-core-peak.webp",
  crossLate: "04-cross-late.webp",
  ignition: "05-ignition.webp",
  crossMid: "06-cross-mid.webp",
  smoke: "07-smoke.webp"
};

const packed = {};
for (const [key, file] of Object.entries(frameFiles)) {
  const buffer = await readFile(path.join(fxDir, file));
  packed[key] = `data:image/webp;base64,${buffer.toString("base64")}`;
}

const source = `"use strict";

// Generated by package-explosion-frames.mjs — Imagine Bomberman-corridor explosion plates.
// CINEMATIC_EXPLOSION_IMAGINE_V1 + CORRIDOR_CROSS_V3 (1024px multi-frame)
const RIFTBOMB_EXPLOSION_FRAME_SOURCES = Object.freeze(${JSON.stringify(packed)});

const RIFTBOMB_EXPLOSION_FRAMES = Object.freeze({
  roles: RIFTBOMB_EXPLOSION_FRAME_SOURCES,
  // Core temporal morph (cross-shaped plates only — no circular fireball hero)
  sequence: Object.freeze([
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.ignition,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.coreCross,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.corePeak,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.crossMid,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.crossLate,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.smoke
  ]),
  // Arm corridor temporal morph
  armSequence: Object.freeze([
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.armCorridor,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.armPeak,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.armCorridor,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.crossLate
  ]),
  // Compat alias
  sources: Object.freeze([
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.ignition,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.coreCross,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.corePeak,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.crossMid,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.crossLate,
    RIFTBOMB_EXPLOSION_FRAME_SOURCES.smoke
  ]),
  armCorridor: RIFTBOMB_EXPLOSION_FRAME_SOURCES.armCorridor,
  coreCross: RIFTBOMB_EXPLOSION_FRAME_SOURCES.coreCross,
  count: 6
});
`;

await writeFile(outputPath, source);
console.log(`Packed explosion corridor frames → ${path.basename(outputPath)}`);
